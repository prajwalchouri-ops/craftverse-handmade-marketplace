  on public.orders for select to authenticated
  using (
    user_id = (select auth.uid())
    or public.current_user_role() = 'admin'
    or public.is_order_artisan(id)
  );

drop policy if exists "Customers can create their own orders" on public.orders;
create policy "Customers can create their own orders"
  on public.orders for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and status = 'Processing'
  );

drop policy if exists "Artisans and admins can update order status" on public.orders;
create policy "Artisans and admins can update order status"
  on public.orders for update to authenticated
  using (
    public.current_user_role() = 'admin'
    or public.is_order_artisan(id)
  )
  with check (
    public.current_user_role() = 'admin'
    or public.is_order_artisan(id)
  );

drop policy if exists "Customers and artisans can read order items" on public.order_items;
create policy "Customers and artisans can read order items"
  on public.order_items for select to authenticated
  using (
    exists (
      select 1 from public.orders o
      where o.id = order_items.order_id
        and (
          o.user_id = (select auth.uid())
          or public.current_user_role() = 'admin'
        )
    )
    or exists (
      select 1 from public.products p
      where p.id = order_items.product_id
        and p.artisan_id = (select auth.uid())
    )
  );

drop policy if exists "Customers can add items to their orders" on public.order_items;
create policy "Customers can add items to their orders"
  on public.order_items for insert to authenticated
  with check (
    exists (
      select 1 from public.orders o
      where o.id = order_items.order_id
        and o.user_id = (select auth.uid())
        and o.status = 'Processing'
    )
  );

drop policy if exists "Anyone can read reviews" on public.reviews;
create policy "Anyone can read reviews"
  on public.reviews for select to anon, authenticated
  using (true);

drop policy if exists "Customers can review delivered purchases" on public.reviews;
create policy "Customers can review delivered purchases"
  on public.reviews for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1
      from public.orders o
      join public.order_items oi on oi.order_id = o.id
      where o.user_id = (select auth.uid())
        and o.status = 'Delivered'
        and oi.product_id = reviews.product_id
    )
  );

drop policy if exists "Customers can update their reviews" on public.reviews;
create policy "Customers can update their reviews"
  on public.reviews for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "Customers can delete their reviews" on public.reviews;
create policy "Customers can delete their reviews"
  on public.reviews for delete to authenticated
  using (user_id = (select auth.uid()));

